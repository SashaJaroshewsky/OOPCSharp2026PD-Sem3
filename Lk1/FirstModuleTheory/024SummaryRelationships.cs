namespace FirstModuleTheory
{
    // Зв'язок        |  Відношенням           |  Хто керує життям частини   | Позначення в UML
    // --------------------------------------------------------------------------------------------------------
    // Асоціація      | знає / використовує    | ніхто, об'єкти незалежні    | суцільна лінія -

    // Агрегація      | має (слабко)           | зовнішній код               | лінія з порожнім ромбом -◇

    // Композиція     | має (сильно)           | ціле                        | лінія із зафарбованим ромбом -◆

    // Наслідування   |  є (клас від класу)    |              -              | суцільна лінія з трикутником -▷

    // Імплементація  |  є (реалізує інтерфейс)|              -              | пунктирна лінія з трикутником - -▷

    // Від найслабшого до найсильнішого:
    // асоціація → агрегація → композиція → наслідування.
    // Загальна порада — "віддавайте перевагу композиції перед наслідуванням" (composition over inheritance):
    // композиція дає менш жорсткий зв'язок між класами і легше змінюється.
}
