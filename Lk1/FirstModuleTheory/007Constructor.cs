namespace FirstModuleTheory._007
{
    internal class MyClass
    {
        // Конструктор (constructor) - це спеціальний метод класу, який викликається під час створення об'єкта цього класу.
        // Він використовується для ініціалізації стану об'єкта та виконання будь-яких необхідних дій під час його створення.
        // Конструктор має ту ж саму назву, що й клас, і не має типу повернення (навіть void).

        // Якщо конструктор не визначений явно, компілятор автоматично створює конструктор за замовчуванням без параметрів.
        public MyClass() // Конструктор за замовчуванням (default constructor) без параметрів
        {
            // Тіло конструктора, де можна виконувати ініціалізацію об'єкта.
            // Тут можна присвоювати значення полям класу, викликати методи або виконувати інші дії, необхідні для підготовки об'єкта до використання.
        }

        // Конструктори можуть мати параметри, що дозволяє передавати значення під час створення об'єкта.
        public MyClass(int a, string b)
        {
        }

        // Можна створювати кілька конструкторів з різними сигнатурами (кількість, типи та порядок параметрів), що дозволяє створювати об'єкти класу з різними початковими станами.
        // Це називається перевантаженням конструкторів (constructor overloading).
        public MyClass(string b, int a)
        {
        }

        // Якщо клас має конструктори з параметрами, але не має конструктора за замовчуванням, то при створенні об'єкта без параметрів виникне помилка компіляції.
    }
}
