namespace FirstModuleTheory._010
{
    // Наслідування дозволяє створювати нові класи на основі існуючих, повторно використовуючи їхній код та розширюючи функціональність.
    // Наслідування в C# реалізується за допомогою двокрапки (:) після імені підкласу, за якою слідує ім'я базового класу.
    // Клас B може додавати нові поля, властивості та методи, а також перевизначати (override) віртуальні методи базового класу.
    // Наслідування є ключовим механізмом об'єктно-орієнтованого програмування (ООП), який сприяє повторному використанню коду та поліморфізму.

    // У C# підтримується лише одиночне наслідування класів, але можна реалізовувати кілька інтерфейсів.
    // "Один клас може наслідувати лише один базовий клас, але може реалізовувати кілька інтерфейсів"

    // Зв'язок "is-a" (є) між підкласом і базовим класом означає, що об'єкт підкласу може використовуватися там, де очікується об'єкт базового класу.
    public class A
    {
    }

    // Клас B є підкласом (derived class), а клас A — базовим класом (base class).
    public class B : A
    {
        // Клас B наслідує (успадковує) всі члени класу A, крім приватних.
    }

    // Якщо в базовому класі є конструктор з параметрами, то підклас повинен явно викликати його через ключове слово base у своєму конструкторі.
    public class Animal
    {
        private string _name;
        public Animal(string name)
        {
            _name = name;
        }
    }

    public class Dog : Animal
    {
        public Dog(string name) : base(name) // Виклик конструктора базового класу Animal з параметром name
        {
        }
    }

    // Можна створювати нескінченну ієрархію наслідування, але в C# не можна наслідувати від sealed класу (закритого для наслідування).
    public sealed class SealedClass // sealed - ключове слово, яке забороняє наслідування від цього класу
    {
    }
    

}
