namespace FirstModuleTheory
{
    // Абстракція (abstraction) — це процес виділення суттєвих характеристик об'єкта та приховування несуттєвих деталей.

    // Абстрактний клас (abstract class) — це клас, який не можна інстанціювати (створювати об'єкти), але можна наслідувати.
    // Визначає загальну поведінку для ГРУПИ похідних класів, які реалізують конкретні деталі.
    // Він може містити абстрактні методи (без реалізації) та звичайні методи (з реалізацією).
    // Абстрактні методи ПОВИННІ бути реалізовані в похідних класах.

    // Абстрактні класи використовуються для створення базових класів, які визначають загальний інтерфейс для ГРУПИ похідних класів.

    // Каже, що має бути реалізованно в похідних класах, але не каже, як саме це має бути реалізовано.

    public abstract class Shape
    {
        // Абстрактний метод - метод без реалізації, який повинен бути реалізований у похідних класах.
        protected abstract double CalculateArea();

        // Визначає загальну поведінку для всіх форм, яка може бути використана без необхідності перевизначення в похідних класах.
        public double GetArea()
        {
            return CalculateArea(); // Виклик абстрактного методу CalculateArea(), який буде реалізований у похідних класах.
        }
    }

    public class Circle : Shape
    {
        private double _radius;
        public Circle(double radius)
        {
            _radius = radius;
        }
        // Реалізація абстрактного методу CalculateArea() для кола.
        sealed protected override double CalculateArea() // override - ключове слово, яке вказує, що метод реалізує абстрактний метод базового класу. 
        {
            return Math.PI * _radius * _radius;
        }
        // sealed - ключове слово, яке забороняє подальше перевизначення цього методу в похідних класах.
    }
}
