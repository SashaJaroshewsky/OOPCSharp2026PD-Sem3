namespace FirstModuleTheory._006
{
    internal class MyClass
    {
        //
        // Автоматично реалізовані властивості (auto-implemented properties) - це властивості, які не мають явного поля для зберігання значення.
        public int MyProperty { get; set; } // Властивість (property) - це член класу, який надає контрольований доступ до значення поля.
                                            // Властивості дозволяють інкапсулювати дані та забезпечують гнучкість у доступі до них.

        public int MyReadOnlyProperty { get; } // Властивість лише для читання (read-only property) -
                                               // це властивість, яка дозволяє лише отримувати значення, але не змінювати його.
                                               //Значення можна присвоїти в ініціалізаторі ({ get; } = 5;)
                                               //або в конструкторі, а після цього вже ні.

        public int MyPrivateProperty { private get; set; } // Властивість з приватним геттером (property with private getter) -
                                                           // це властивість, яка дозволяє лише встановлювати значення, але не отримувати його ззовні класу.

        public int MyPrivateSetProperty { get; private set; } // Властивість з приватним сеттером (property with private setter) -
                                                              // це властивість, яка дозволяє лише отримувати значення, але не змінювати його ззовні класу.
        //

        private int _myField; // Приватне поле, доступне лише всередині класу MyClass.
        public int MyPropertyWithBackingField // Властивість з полем-підкладкою (property with backing field) -
                                              // це властивість, яка використовує приватне поле для зберігання значення.
        {
            get { return _myField; }  // Геттер (getter) - це метод, який повертає значення властивості.
            set { _myField = value; } // Сеттер (setter) - це метод, який встановлює значення властивості.
                                      //  value - неявний параметр сеттера, що містить нове значення.
        }


        // Обчислювана властивість - не зберігає значення, а обчислює його щоразу.
        public int MyComputableProperty => _myField * 2;

        // init-аксесор (C# 9) - значення можна задати лише під час створення об'єкта:
        // new MyClass { Id = 1 }, а потім змінити вже не можна.
        public int Id { get; init; }

        // required (C# 11) - компілятор вимагає задати властивість під час створення об'єкта.
        public required string Code { get; init; }

        // Ключове слово field (C# 14) - доступ до згенерованого поля-підкладки
        // без оголошення власного поля.
        public string? Title
        {
            get;
            set => field = value;
        }
    }
}
