namespace FirstModuleTheory._005
{
    internal class MyClass
    {
        public int MyField; // Поле (field) - це змінна, яка є членом класу і використовується для зберігання стану об'єкта.
        private int _myPrivateField; // Приватне поле, доступне лише всередині класу MyClass.

        int _withoutAccessModifier; // Поле без модифікатора доступу, за замовчуванням private, доступне лише всередині класу MyClass.
    }
}


