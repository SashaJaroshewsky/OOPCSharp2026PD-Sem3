namespace FirstModuleTheory._016
{
    // Інтерфейс (interface) - це контракт, який визначає набір методів та властивостей, які клас повинен реалізувати.

    // Інтерфейси дозволяють реалізовувати поліморфізм та забезпечують гнучкість у архітектурі програм.
    // Інтерфейси не можуть містити реалізацію методів (до C# 8.0), а лише їх сигнатури.
    // За замовчуванням, всі члени інтерфейсу є публічними (public), а сам інтерфейс internal
    internal interface IMyInterface
    {
        int MyProperty { get; } // Властивість (property) - це член інтерфейсу, який дозволяє отримувати значення.

        void MyMethod(); // Метод (method) - це член інтерфейсу, який визначає поведінку, яку клас повинен реалізувати.
    }

    // Клас MyClass реалізує інтерфейс IMyInterface,
    // що означає, що він повинен надати реалізацію для всіх методів та властивостей, визначених в інтерфейсі.
    // Зв'язок між класом та інтерфейсом називається "implements" (реалізація інтерфейсу, імплементація)
    // Імплементіція (Значення слова) - це процес фактичного втілення в життя планів, ідей, проєктів, стандартів, законів чи рішень.
    // У контексті програмування, імплементація означає реалізацію інтерфейсу або абстрактного класу в конкретному класі.
    public class MyClass : IMyInterface
    {
        public int MyProperty { get; private set; } // Реалізація властивості з інтерфейсу.
                                                    // Модифікатор доступу private set дозволяє змінювати значення властивості лише всередині класу MyClass.
                                                    // Контракт інтерфейсу вимагає лише наявності геттера (get), тому сеттер (set) може бути приватним.
                                                    
        public void MyMethod()
        {
            // Реалізація методу з інтерфейсу
        }
    }

    // Клас може реалізовувати кілька інтерфейсів, що дозволяє комбінувати різні функціональні можливості.
    public interface IAnotherInterface
    {
        void AnotherMethod();
    }

    public class MyClassWithMultipleInterfaces : IMyInterface, IAnotherInterface // клас імплементує інтерфейси
    {
        public int MyProperty { get; private set; }
        public void MyMethod()
        {
            // Реалізація методу з IMyInterface
        }
        public void AnotherMethod()
        {
            // Реалізація методу з IAnotherInterface
        }
    }

    // Інтерфейс може наслідуватись від інших інтерфейсів
    interface IMyInterface2 : IMyInterface // Інтерфейс наслідується від інтерфейсу
    {

    }
}
