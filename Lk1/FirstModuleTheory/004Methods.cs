namespace FirstModuleTheory._004
{
    internal class MyClass
    {
        // Методи (methods) - це функції, які визначені всередині класу та описують поведінку об'єктів цього класу.
        // Методи можуть приймати параметри, виконувати певні дії та повертати значення.
        // Вони дозволяють організувати код у логічні блоки та повторно використовувати його.
        // Методи є основним механізмом реалізації поведінки об'єктів у ООП.
        
        public void MyMethod()
        {
            // Тіло методу, де описується його поведінка.
            // Тут можна виконувати різні дії, наприклад, обчислення, виведення інформації, зміну стану об'єкта тощо.
        }

        // Методи можуть мати різні модифікатори доступу (public, private, protected, internal), які визначають, звідки можна викликати цей метод.
        // Методи можуть повертати значення певного типу або бути void (не повертати значення).

        // Методи мають різні сигнатури.
        // Сигнатура методу — це сукупність імені методу та списку його параметрів
        // (кількість, типи, порядок і модифікатори ref, out, in),
        // яка однозначно ідентифікує метод у межах класу.
        // Саме за сигнатурою компілятор розрізняє перевантажені методи.

        // В класі не може бути двох методів з однаковою сигнатурою.

        // Яка сигнатура цього методу?
        public void MyMethod(int a, string b)
        {
        }

        // Помилка: методи з однаковою сигнатурою не можуть існувати в одному класі.
        //public int MyMethod(int a, string b) // модифікатор доступу та тип повернення не враховуються при визначенні сигнатури методу
        //{ 
        //}

        // Якщо відсутній модифікатор доступу, то за замовчуванням використовується private, який обмежує доступ до методу лише межами класу.
        void MyMethod(string b, int a) // сигнатура цього методу відрізняється від попереднього, бо порядок параметрів інший
        {
        }

    }
}
