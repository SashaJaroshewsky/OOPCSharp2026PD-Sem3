namespace FirstModuleTheory
{
    // Об'єктно-орієнтоване програмування (ООП) — це парадигма програмування, в якій програма
    // розглядається як набір взаємодіючих між собою об'єктів. Кожен об'єкт поєднує дані (стан)
    // та поведінку (методи), що працюють з цими даними.

    // Клас (Class) — це шаблон (опис типу), який визначає, які дані та поведінку матимуть об'єкти.
    // Об'єкт (Object) — це конкретний екземпляр класу, створений за допомогою оператора new.

    // ООП базується на трьох основних принципах: інкапсуляція, наслідування та поліморфізм.
    // Четвертим принципом, який часто додають до списку, є абстракція.

    // Інкапсуляція (Encapsulation) — це принцип ООП, який об'єднує дані та методи роботи з ними
    // в одному класі, приховує внутрішню реалізацію об'єкта та надає доступ до його стану
    // й поведінки лише через визначений публічний інтерфейс (методи та властивості).
    // Реалізується за допомогою модифікаторів доступу (private, protected, internal, public) та властивостей.
    // Мета — захистити об'єкт від некоректних змін ззовні та зменшити залежність від деталей реалізації.

    // Наслідування (Inheritance) — це принцип ООП, який дозволяє створювати новий клас (похідний, дочірній)
    // на основі існуючого (базового, батьківського), успадковуючи його поля, властивості та методи,
    // а також розширювати або змінювати їхню поведінку.
    // У C# клас може наслідувати лише один базовий клас (class Dog : Animal),
    // але може реалізовувати кілька інтерфейсів (class Dog : Animal, IComparable, IDisposable).
    // Усі класи неявно наслідуються від System.Object.
    // Мета — повторне використання коду та побудова ієрархії типів (відношення "є": собака Є твариною).

    // Поліморфізм (Polymorphism) — це принцип ООП, який дозволяє працювати з об'єктами різних типів
    // через спільний інтерфейс, при цьому кожен об'єкт поводиться відповідно до свого фактичного типу.
    // Види поліморфізму в C#:
    //   - поліморфізм підтипів (динамічний, під час виконання) — перевизначення методів
    //     за допомогою virtual / override або реалізація абстрактних методів та інтерфейсів:
    //     Animal a = new Dog(); a.Speak(); // викличеться Dog.Speak()
    //   - параметричний — узагальнення (generics): List<T>, Swap<T>(ref T a, ref T b) // Ще будемо вчити
    //   - ad hoc (статичний, під час компіляції) — перевантаження методів та операторів
    //     (методи з однаковим ім'ям, але різною сигнатурою).
    // Мета — писати загальний код, який працює з будь-якими нащадками без перевірки конкретного типу.

    // Абстракція (Abstraction) — це принцип ООП, який полягає у виділенні лише суттєвих для задачі
    // характеристик і поведінки об'єкта та відкиданні несуттєвих деталей.
    // Абстракція визначає, ЩО робить об'єкт, а не ЯК він це робить.
    // Реалізується за допомогою абстрактних класів (abstract class) та інтерфейсів (interface),
    // які описують контракт без конкретної (або з частковою) реалізацією.
    // Мета — спростити складну систему та зменшити залежність коду від конкретних реалізацій.

    // Різниця між абстракцією та інкапсуляцією:
    //   абстракція — це про те, ЩО показати (який контракт надає об'єкт);
    //   інкапсуляція — це про те, ЯК приховати (захист внутрішнього стану та реалізації).
}
