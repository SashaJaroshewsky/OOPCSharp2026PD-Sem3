namespace FirstModuleTheory._002
{
    internal class MyClass
    {
    }

    internal class MyClass2 //Клас для демонстрації створення об'єкта класу MyClass
    {
        public void MyMethod()
        {
            MyClass myClass; // Створення змінної типу MyClass
            new MyClass(); // Створення об'єкта класу MyClass за допомогою оператора new 

            // new - оператор, який використовується для створення нового об'єкта класу.
            // MyClass() - виклик конструктора класу MyClass, який ініціалізує новий об'єкт.

            myClass = new MyClass(); // Присвоєння посилання на об'єкт класу MyClass змінній myClass
            // = оператор присвоєння, який використовується для присвоєння значення змінній.
            // в змінній myClass зберігається посилання на об'єкт класу MyClass, створений у пам'яті.

            // Об'єкт класу (Instance, екземпляр класу) - це конкретна реалізація певного класу,
            // що існує в пам'яті комп'ютера та має власний унікальний стан (значення полів) та поведінку (методи).
        }
    }
}
