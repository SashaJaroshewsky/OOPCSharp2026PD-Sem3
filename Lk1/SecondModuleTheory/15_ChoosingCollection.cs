namespace SecondModuleTheory.ChoosingCollection
{
    // ПІДСУМОК: ЯКУ КОЛЕКЦІЮ ОБРАТИ?
    //
    // Що потрібно в задачі                                       -> Що обрати
    // -----------------------------------------------------------------------------------------
    // Кількість елементів відома і не зміниться                  -> масив T[]
    // Звичайний список: важливий порядок, доступ за індексом     -> List<T>
    // Швидко знаходити значення за ключем (id, ім'я, код)        -> Dictionary<TKey, TValue>
    // Лише унікальні елементи / часто питаємо "чи є такий?"      -> HashSet<T>
    // Обробляти в порядку надходження (FIFO)                     -> Queue<T>
    // Брати останній доданий (LIFO), скасування дій              -> Stack<T>
    // Те саме, що множина чи словник, але завжди відсортоване    -> SortedSet<T>, SortedDictionary<TKey, TValue>
    //
    // ШВИДКІСТЬ ОСНОВНИХ ОПЕРАЦІЙ
    // Нотація O ("О велике") показує, як зростає час операції зі зростанням кількості елементів n:
    //   O(1) - час не залежить від кількості елементів (миттєво)
    //   O(n) - час зростає пропорційно кількості елементів (треба перебрати всі)
    //
    //   Операція                          List<T>     Dictionary     HashSet    Queue / Stack
    //   Додати                            O(1)*       O(1)*          O(1)*      O(1)*
    //   Доступ за індексом / ключем       O(1)        O(1)           -          -
    //   Перевірка "чи є елемент"          O(n)        O(1) за ключем O(1)       O(n)
    //   Видалення                         O(n)        O(1)           O(1)       O(1) з краю
    //   * у середньому: час від часу колекції треба розширити внутрішнє сховище
    //
    // ЗАГАЛЬНІ ПРАВИЛА
    // 1. Не впевнені - беріть List<T>.
    // 2. Не використовуйте ArrayList і Hashtable у новому коді - лише узагальнені колекції.
    // 3. У параметрах методів часто вказують інтерфейс (IEnumerable<T>, ICollection<T>, IList<T>),
    //    щоб метод приймав будь-яку відповідну колекцію.
    // 4. Не змінюйте колекцію всередині foreach по ній самій.
}
